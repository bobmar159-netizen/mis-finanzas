-- PROPUESTA P0.5. No ejecutar sin revisión y autorización explícita.
-- Separa conversaciones del dueño de CRM/comercial y no almacena teléfonos
-- legibles: la identidad se representa mediante un HMAC calculado por backend.
begin;

do $$
begin
  if to_regclass('auth.users') is null then
    raise exception 'owner_personal_requires_auth_users';
  end if;
  if to_regclass('public.yarbi_owner_authorized_identities') is not null
     or to_regclass('public.yarbi_owner_personal_conversations') is not null
     or to_regclass('public.yarbi_owner_personal_messages') is not null
     or to_regclass('public.yarbi_owner_provider_events') is not null
     or to_regclass('public.yarbi_owner_personal_audio_assets') is not null then
    raise exception 'owner_personal_objects_already_exist_manual_contract_review_required';
  end if;
end $$;

create table public.yarbi_owner_authorized_identities (
  id bigint generated by default as identity primary key,
  owner_account_id uuid not null references auth.users(id) on delete cascade,
  owner_key text not null check (length(btrim(owner_key)) between 1 and 80),
  provider text not null check (provider = 'whatsapp'),
  identity_fingerprint text not null check (identity_fingerprint ~ '^[a-f0-9]{64}$'),
  status text not null default 'active' check (status in ('active','revoked')),
  label text,
  created_at timestamptz not null default now(),
  revoked_at timestamptz,
  unique(provider, identity_fingerprint),
  unique(owner_account_id, owner_key, provider, identity_fingerprint),
  check ((status = 'active' and revoked_at is null) or (status = 'revoked' and revoked_at is not null))
);

create table public.yarbi_owner_personal_conversations (
  id bigint generated by default as identity primary key,
  owner_account_id uuid not null references auth.users(id) on delete cascade,
  owner_key text not null check (length(btrim(owner_key)) between 1 and 80),
  channel text not null default 'whatsapp_personal' check (channel = 'whatsapp_personal'),
  processing_state text not null default 'active' check (processing_state in ('active','paused','closed')),
  retention_until timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(owner_account_id, owner_key, channel)
);

create table public.yarbi_owner_provider_events (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.yarbi_owner_personal_conversations(id) on delete cascade,
  provider text not null check (provider in ('ycloud','meta_cloud')),
  event_fingerprint text not null check (event_fingerprint ~ '^[a-f0-9]{64}$'),
  provider_event_type text not null check (length(btrim(provider_event_type)) between 1 and 100),
  received_at timestamptz not null default now(),
  authenticated_at timestamptz not null,
  processing_state text not null default 'received' check (processing_state in ('received','processing','processed','rejected','failed')),
  operation_id text,
  error_code text,
  unique(provider, event_fingerprint)
);

create table public.yarbi_owner_personal_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.yarbi_owner_personal_conversations(id) on delete cascade,
  provider_event_id bigint not null unique references public.yarbi_owner_provider_events(id) on delete restrict,
  provider_message_fingerprint text not null check (provider_message_fingerprint ~ '^[a-f0-9]{64}$'),
  direction text not null check (direction in ('incoming','outgoing')),
  content_ciphertext bytea,
  content_format text not null default 'text' check (content_format in ('text','audio','image','document','system')),
  redacted_preview text,
  message_at timestamptz not null,
  retention_until timestamptz,
  created_at timestamptz not null default now(),
  check (content_ciphertext is not null or redacted_preview is not null),
  unique(conversation_id, provider_message_fingerprint)
);

create table public.yarbi_owner_personal_audio_assets (
  id bigint generated by default as identity primary key,
  message_id bigint not null unique references public.yarbi_owner_personal_messages(id) on delete cascade,
  media_fingerprint text not null unique check (media_fingerprint ~ '^[a-f0-9]{64}$'),
  mime_type text not null check (mime_type in ('audio/ogg','audio/opus','audio/mpeg','audio/mp4','audio/aac','audio/webm')),
  size_bytes integer not null check (size_bytes > 0 and size_bytes <= 16777216),
  duration_ms integer check (duration_ms > 0 and duration_ms <= 600000),
  storage_key text,
  expires_at timestamptz not null,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  check ((deleted_at is null and storage_key is not null) or (deleted_at is not null and storage_key is null))
);

create index yarbi_owner_personal_conversations_owner_idx
  on public.yarbi_owner_personal_conversations(owner_account_id, owner_key, updated_at desc);
create index yarbi_owner_provider_events_state_idx
  on public.yarbi_owner_provider_events(processing_state, received_at asc);
create index yarbi_owner_personal_messages_conversation_time_idx
  on public.yarbi_owner_personal_messages(conversation_id, message_at desc);
create index yarbi_owner_personal_audio_expiry_idx
  on public.yarbi_owner_personal_audio_assets(expires_at) where deleted_at is null;

alter table public.yarbi_owner_authorized_identities enable row level security;
alter table public.yarbi_owner_personal_conversations enable row level security;
alter table public.yarbi_owner_provider_events enable row level security;
alter table public.yarbi_owner_personal_messages enable row level security;
alter table public.yarbi_owner_personal_audio_assets enable row level security;

revoke all on table public.yarbi_owner_authorized_identities, public.yarbi_owner_personal_conversations,
  public.yarbi_owner_provider_events, public.yarbi_owner_personal_messages, public.yarbi_owner_personal_audio_assets
  from public, anon, authenticated;
grant select, insert, update on table public.yarbi_owner_authorized_identities, public.yarbi_owner_personal_conversations,
  public.yarbi_owner_provider_events, public.yarbi_owner_personal_messages, public.yarbi_owner_personal_audio_assets to service_role;

do $$
declare sequence_name text;
begin
  foreach sequence_name in array array[
    pg_get_serial_sequence('public.yarbi_owner_authorized_identities','id'),
    pg_get_serial_sequence('public.yarbi_owner_personal_conversations','id'),
    pg_get_serial_sequence('public.yarbi_owner_provider_events','id'),
    pg_get_serial_sequence('public.yarbi_owner_personal_messages','id'),
    pg_get_serial_sequence('public.yarbi_owner_personal_audio_assets','id')
  ] loop
    if sequence_name is null then raise exception 'owner_personal_identity_sequence_missing'; end if;
    execute format('revoke all on sequence %s from public, anon, authenticated', sequence_name);
    execute format('grant usage, select on sequence %s to service_role', sequence_name);
  end loop;
end $$;

commit;
