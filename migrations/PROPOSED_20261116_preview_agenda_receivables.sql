-- Supabase Preview only. Adds the canonical remote Agenda contract already
-- consumed by approve.js/collections.js; no rows are imported or synthesized.
-- Requires the existing CRM contact primary key to remain bigint.
begin;

do $$
declare
  crm_id_type text;
begin
  if to_regclass('public.crm_contacts') is null then
    raise exception 'preview_agenda_requires_crm_contacts';
  end if;
  if to_regclass('public.yarbi_owner_contact_scope') is null then
    raise exception 'preview_agenda_requires_owner_contact_scope';
  end if;
  select data_type into crm_id_type
    from information_schema.columns
   where table_schema = 'public' and table_name = 'crm_contacts' and column_name = 'id';
  if crm_id_type is distinct from 'bigint' then
    raise exception 'preview_agenda_crm_id_incompatible:%', coalesce(crm_id_type, '<missing>');
  end if;
  if to_regclass('public.agenda_events') is not null or to_regclass('public.yarbi_receivables') is not null then
    raise exception 'preview_agenda_or_receivables_exists_review_contract_before_applying';
  end if;
end;
$$;

create table public.agenda_events (
  id bigint generated by default as identity primary key,
  contact_id bigint references public.crm_contacts(id) on delete set null,
  event_type text not null,
  title text not null check (char_length(title) between 1 and 240),
  service text,
  description text,
  location text,
  maps_url text,
  latitude numeric(9,6),
  longitude numeric(9,6),
  starts_at timestamptz,
  ends_at timestamptz,
  timezone text not null default 'America/Lima',
  status text not null default 'pending',
  source text not null default 'legacy',
  dedupe_key text,
  price numeric(12,2) check (price is null or price >= 0),
  service_details jsonb not null default '[]'::jsonb check (jsonb_typeof(service_details) = 'array'),
  parent_event_id bigint references public.agenda_events(id) on delete set null,
  parent_local_id text,
  local_ref text,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at is null or starts_at is null or ends_at >= starts_at),
  check ((latitude is null and longitude is null) or (latitude between -90 and 90 and longitude between -180 and 180))
);

create unique index agenda_events_yarbi_dedupe_key_uq
  on public.agenda_events (dedupe_key)
  where source = 'yarbi_form' and dedupe_key is not null;
create index agenda_events_contact_starts_search_idx
  on public.agenda_events (contact_id, starts_at desc);
create index agenda_events_source_local_ref_idx
  on public.agenda_events (source, local_ref)
  where local_ref is not null;
create index agenda_events_parent_event_idx
  on public.agenda_events (parent_event_id)
  where parent_event_id is not null;

create table public.yarbi_receivables (
  id bigint generated by default as identity primary key,
  agenda_event_id bigint not null unique references public.agenda_events(id) on delete restrict,
  contact_id bigint references public.crm_contacts(id) on delete set null,
  client_name text,
  agreed_amount numeric(12,2) not null check (agreed_amount > 0),
  paid_amount numeric(12,2) not null check (paid_amount >= 0),
  balance_amount numeric(12,2) not null check (balance_amount >= 0),
  status text not null check (status in ('paid','partial','unpaid')),
  next_action text,
  next_action_due date,
  source text not null check (source = 'yarbi_daily_close'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (paid_amount + balance_amount = agreed_amount),
  check ((balance_amount = 0 and status = 'paid') or (balance_amount > 0 and paid_amount > 0 and status = 'partial') or (balance_amount > 0 and paid_amount = 0 and status = 'unpaid'))
);

create index yarbi_receivables_contact_status_search_idx
  on public.yarbi_receivables (contact_id, status, updated_at desc);
create index yarbi_receivables_open_idx
  on public.yarbi_receivables (updated_at desc)
  where status <> 'paid';

create function public.yarbi_preview_touch_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
revoke all on function public.yarbi_preview_touch_updated_at() from public, anon, authenticated;
create trigger agenda_events_touch_updated_at
  before update on public.agenda_events
  for each row execute function public.yarbi_preview_touch_updated_at();
create trigger yarbi_receivables_touch_updated_at
  before update on public.yarbi_receivables
  for each row execute function public.yarbi_preview_touch_updated_at();

alter table public.agenda_events enable row level security;
alter table public.agenda_events force row level security;
alter table public.yarbi_receivables enable row level security;
alter table public.yarbi_receivables force row level security;
revoke all on public.agenda_events, public.yarbi_receivables from public, anon, authenticated;
grant select, insert, update, delete on public.agenda_events, public.yarbi_receivables to service_role;
grant usage, select on sequence public.agenda_events_id_seq, public.yarbi_receivables_id_seq to service_role;

commit;
