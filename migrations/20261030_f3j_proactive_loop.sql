-- Fase 3J: estado mínimo del loop proactivo e inbox interno del dueño.
-- Candidata exclusiva para yarbi-audit-preview; no contiene datos comerciales.
begin;

do $$
begin
  if to_regclass('public.crm_contacts') is null or to_regclass('public.yarbi_contact_operational_memory') is null then
    raise exception 'F3J: faltan contratos 3A/3E requeridos';
  end if;
  if to_regclass('public.yarbi_proactive_runs') is not null
     or to_regclass('public.yarbi_owner_notification_state') is not null
     or to_regclass('public.yarbi_owner_inbox') is not null then
    raise exception 'F3J: ya existen objetos de loop; se requiere revisión explícita';
  end if;
end
$$;

create table public.yarbi_proactive_runs (
  id bigint generated by default as identity primary key,
  run_key text not null unique check (length(btrim(run_key)) between 1 and 180),
  owner_key text not null default 'primary' check (length(btrim(owner_key)) between 1 and 80),
  status text not null check (status in ('running','completed','deferred','delivery_suppressed','not_due_yet','no_candidates','failed')),
  started_at timestamptz not null,
  completed_at timestamptz,
  evaluated_contacts integer not null default 0 check (evaluated_contacts >= 0),
  actionable_count integer not null default 0 check (actionable_count >= 0),
  brief_decision text check (brief_decision in ('notify','defer','no_notification','escalate')),
  notification_fingerprint text,
  next_review_at timestamptz,
  error_code text,
  metrics jsonb not null default '{}'::jsonb check (jsonb_typeof(metrics) = 'object'),
  created_at timestamptz not null default now(),
  check ((status = 'running' and completed_at is null) or (status <> 'running' and completed_at is not null))
);

create table public.yarbi_owner_notification_state (
  owner_key text primary key check (length(btrim(owner_key)) between 1 and 80),
  last_notified_at timestamptz,
  last_fingerprint text,
  recent_fingerprints jsonb not null default '[]'::jsonb check (jsonb_typeof(recent_fingerprints) = 'array'),
  last_escalated_at timestamptz,
  next_review_at timestamptz,
  updated_at timestamptz not null default now()
);

create table public.yarbi_owner_inbox (
  id bigint generated by default as identity primary key,
  run_id bigint not null references public.yarbi_proactive_runs(id) on delete restrict,
  owner_key text not null references public.yarbi_owner_notification_state(owner_key) on delete restrict,
  fingerprint text not null check (length(btrim(fingerprint)) between 1 and 160),
  urgency text not null check (urgency in ('low','medium','high','urgent')),
  notification_mode text not null check (notification_mode in ('interrupt','digest')),
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  status text not null default 'delivered' check (status in ('prepared','delivered','suppressed','failed')),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  dismissed_at timestamptz
);

create index yarbi_proactive_runs_recent_idx on public.yarbi_proactive_runs(owner_key, started_at desc);
create index yarbi_owner_inbox_active_idx on public.yarbi_owner_inbox(owner_key, created_at desc) where dismissed_at is null;
create index yarbi_proactive_candidate_contacts_idx on public.crm_contacts(commercial_status, last_contact_at desc);

alter table public.yarbi_proactive_runs enable row level security;
alter table public.yarbi_owner_notification_state enable row level security;
alter table public.yarbi_owner_inbox enable row level security;
revoke all on table public.yarbi_proactive_runs, public.yarbi_owner_notification_state, public.yarbi_owner_inbox from public, anon, authenticated;
grant select, insert, update on table public.yarbi_proactive_runs, public.yarbi_owner_notification_state, public.yarbi_owner_inbox to service_role;

do $$
declare sequence_name text;
begin
  foreach sequence_name in array array[
    pg_get_serial_sequence('public.yarbi_proactive_runs','id'),
    pg_get_serial_sequence('public.yarbi_owner_inbox','id')
  ] loop
    if sequence_name is null then raise exception 'F3J: secuencia identity no encontrada'; end if;
    execute format('revoke all on sequence %s from public, anon, authenticated', sequence_name);
    execute format('grant usage, select on sequence %s to service_role', sequence_name);
  end loop;
end
$$;

create function public.claim_yarbi_proactive_run(p_run_key text, p_owner_key text, p_started_at timestamptz)
returns table(claimed boolean, run_id bigint, status text)
language plpgsql security invoker set search_path = public, pg_temp as $$
declare inserted_id bigint;
begin
  if nullif(btrim(p_run_key), '') is null or nullif(btrim(p_owner_key), '') is null or p_started_at is null then
    raise exception 'proactive_run_reference_invalid' using errcode='22023';
  end if;
  insert into public.yarbi_proactive_runs(run_key, owner_key, status, started_at)
  values (btrim(p_run_key), btrim(p_owner_key), 'running', p_started_at)
  on conflict (run_key) do nothing returning id into inserted_id;
  if inserted_id is null then
    select run_row.id, run_row.status into run_id, status from public.yarbi_proactive_runs run_row where run_row.run_key=btrim(p_run_key);
    claimed := false; return next;
  end if;
  claimed := true; run_id := inserted_id; status := 'running'; return next;
end;
$$;

create function public.complete_yarbi_proactive_run(
  p_run_id bigint, p_status text, p_completed_at timestamptz, p_next_review_at timestamptz,
  p_metrics jsonb, p_brief_decision text, p_notification_fingerprint text, p_error_code text
) returns table(completed boolean)
language plpgsql security invoker set search_path = public, pg_temp as $$
begin
  if p_run_id is null or p_completed_at is null or p_status not in ('completed','deferred','delivery_suppressed','not_due_yet','no_candidates','failed') then
    raise exception 'proactive_run_completion_invalid' using errcode='22023';
  end if;
  update public.yarbi_proactive_runs
     set status=p_status, completed_at=p_completed_at, next_review_at=p_next_review_at,
         metrics=coalesce(p_metrics, '{}'::jsonb), evaluated_contacts=coalesce((p_metrics->>'contexts')::integer, 0),
         actionable_count=coalesce((p_metrics->>'actionable')::integer, 0), brief_decision=p_brief_decision,
         notification_fingerprint=p_notification_fingerprint, error_code=p_error_code
   where id=p_run_id and status='running';
  completed := found; return next;
end;
$$;

create function public.list_yarbi_proactive_candidates(p_as_of timestamptz, p_limit integer)
returns table(contact_id bigint, opportunity_id text, estimated_value numeric, scheduled_visit_at timestamptz, last_owner_action_at timestamptz)
language sql security invoker set search_path = public, pg_temp stable as $$
  select cc.id, 'contact:' || cc.id::text, null::numeric, null::timestamptz, null::timestamptz
    from public.crm_contacts cc
   where cc.commercial_status in ('frio','tibio','caliente')
     and (
       cc.last_contact_at >= p_as_of - interval '30 days'
       or exists (
         select 1 from public.yarbi_contact_operational_memory om
          where om.contact_id=cc.id and om.state='active'
            and om.memory_type in ('pending_step','visit','customer_commitment','business_commitment')
       )
     )
   order by cc.last_contact_at desc nulls last, cc.id desc
   -- LIMIT requiere una expresión parentetizada cuando se calcula con funciones.
   limit (least(greatest(coalesce(p_limit, 50), 1), 200))
$$;

create function public.record_yarbi_proactive_evaluation(
  p_run_id bigint, p_owner_key text, p_status text, p_next_review_at timestamptz,
  p_brief_decision text, p_notification_fingerprint text, p_metrics jsonb
) returns table(recorded boolean)
language plpgsql security invoker set search_path = public, pg_temp as $$
begin
  if p_run_id is null or nullif(btrim(p_owner_key), '') is null then raise exception 'proactive_evaluation_reference_invalid' using errcode='22023'; end if;
  insert into public.yarbi_owner_notification_state(owner_key) values (btrim(p_owner_key)) on conflict (owner_key) do nothing;
  update public.yarbi_owner_notification_state set next_review_at=p_next_review_at, updated_at=now() where owner_key=btrim(p_owner_key);
  recorded := true; return next;
end;
$$;

create function public.deliver_yarbi_owner_brief(
  p_run_id bigint, p_owner_key text, p_fingerprint text, p_urgency text, p_notification_mode text,
  p_payload jsonb, p_now timestamptz
) returns table(outcome text, inbox_id bigint)
language plpgsql security invoker set search_path = public, pg_temp as $$
declare existing_id bigint; state_row public.yarbi_owner_notification_state%rowtype;
begin
  if p_run_id is null or nullif(btrim(p_owner_key), '') is null or nullif(btrim(p_fingerprint), '') is null
     or p_urgency not in ('low','medium','high','urgent') or p_notification_mode not in ('interrupt','digest')
     or p_payload is null or jsonb_typeof(p_payload) <> 'object' or p_now is null then
    raise exception 'proactive_delivery_contract_invalid' using errcode='22023';
  end if;
  insert into public.yarbi_owner_notification_state(owner_key) values (btrim(p_owner_key)) on conflict (owner_key) do nothing;
  perform pg_advisory_xact_lock(hashtext('yarbi-owner-inbox:' || btrim(p_owner_key))::bigint);
  select * into state_row from public.yarbi_owner_notification_state where owner_key=btrim(p_owner_key) for update;
  select id into existing_id from public.yarbi_owner_inbox
   where owner_key=btrim(p_owner_key) and fingerprint=btrim(p_fingerprint) and created_at >= p_now - interval '24 hours'
     and status in ('prepared','delivered') order by id desc limit 1;
  if existing_id is not null then outcome := 'duplicate_recent_notification'; inbox_id := existing_id; return next; return; end if;
  insert into public.yarbi_owner_inbox(run_id, owner_key, fingerprint, urgency, notification_mode, payload, status)
  values (p_run_id, btrim(p_owner_key), btrim(p_fingerprint), p_urgency, p_notification_mode, p_payload, 'delivered') returning id into inbox_id;
  update public.yarbi_owner_notification_state
     set last_notified_at=p_now, last_fingerprint=btrim(p_fingerprint),
         last_escalated_at=case when p_urgency='urgent' then p_now else state_row.last_escalated_at end,
         recent_fingerprints=(select coalesce(jsonb_agg(entry order by ordinal desc), '[]'::jsonb) from (
           select entry, ordinal from jsonb_array_elements(coalesce(state_row.recent_fingerprints, '[]'::jsonb) || jsonb_build_array(jsonb_build_object('fingerprint', btrim(p_fingerprint), 'notified_at', p_now))) with ordinality as e(entry, ordinal)
           order by ordinal desc limit 20
         ) recent), updated_at=now()
   where owner_key=btrim(p_owner_key);
  outcome := 'delivered'; return next;
end;
$$;

revoke all on function public.claim_yarbi_proactive_run(text,text,timestamptz), public.complete_yarbi_proactive_run(bigint,text,timestamptz,timestamptz,jsonb,text,text,text), public.list_yarbi_proactive_candidates(timestamptz,integer), public.record_yarbi_proactive_evaluation(bigint,text,text,timestamptz,text,text,jsonb), public.deliver_yarbi_owner_brief(bigint,text,text,text,text,jsonb,timestamptz) from public, anon, authenticated;
grant execute on function public.claim_yarbi_proactive_run(text,text,timestamptz), public.complete_yarbi_proactive_run(bigint,text,timestamptz,timestamptz,jsonb,text,text,text), public.list_yarbi_proactive_candidates(timestamptz,integer), public.record_yarbi_proactive_evaluation(bigint,text,text,timestamptz,text,text,jsonb), public.deliver_yarbi_owner_brief(bigint,text,text,text,text,jsonb,timestamptz) to service_role;

